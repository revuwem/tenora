#!/usr/bin/env bash
# Run the dev or prod Docker stack so several git worktrees can run side by side.
#
#   scripts/docker.sh <dev|prod> <docker compose args...>
#   scripts/docker.sh dev up --build -V
#   scripts/docker.sh dev down
#   scripts/docker.sh dev ports        # print this worktree's URLs
#
# Main checkout: compose defaults (project tenora-<mode>, ports 3000 / 8000).
# Linked worktree: its own project name (tenora-<mode>-<dir>-<hash>) and its own
# free host ports, picked once and saved in .env.docker.local (gitignored) so
# they stay stable between runs. Delete that file to pick new ones.
set -euo pipefail

usage() {
  echo "usage: $0 <dev|prod> <docker compose args...>" >&2
  exit 2
}

mode="${1:-}"
[[ "$mode" == "dev" || "$mode" == "prod" ]] || usage
shift

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd -P)"
cd "$root"
compose_file="docker-compose.$mode.yml"
env_file=".env.docker.local"

# Linked worktrees have a .git *file*; the main checkout has a .git directory.
is_worktree=false
[[ -f .git ]] && is_worktree=true

port_in_use() {
  (exec 3<>"/dev/tcp/127.0.0.1/$1") 2>/dev/null
}

# Ports already claimed by other worktrees' env files (even if not running now).
reserved_ports() {
  git worktree list --porcelain 2>/dev/null | sed -n 's/^worktree //p' | while read -r wt; do
    [[ "$wt" == "$root" ]] && continue
    [[ -f "$wt/$env_file" ]] && sed -n -E 's/^(WEB|API)_PORT=//p' "$wt/$env_file"
  done || true
  return 0
}

if $is_worktree; then
  if [[ ! -f "$env_file" ]]; then
    dir="$(basename "$root" | tr '[:upper:]' '[:lower:]' | sed -E 's/[^a-z0-9_-]+/-/g; s/^[^a-z0-9]+//')"
    # Short hash of the full path keeps same-named worktrees in different folders apart.
    hash="$(printf '%s' "$root" | cksum | cut -d' ' -f1)"
    slug="${dir:-wt}-$(printf '%04x' $((hash % 65536)))"

    reserved=" $(reserved_ports | tr '\n' ' ') "
    start=$((hash % 99 + 1))
    web="" api=""
    for i in $(seq 0 98); do
      n=$(((start - 1 + i) % 99 + 1))
      w=$((3000 + n))
      a=$((8000 + n))
      [[ "$reserved" == *" $w "* || "$reserved" == *" $a "* ]] && continue
      port_in_use "$w" || port_in_use "$a" || {
        web=$w
        api=$a
        break
      }
    done
    [[ -n "$web" ]] || { echo "no free port pair found in 3001-3099 / 8001-8099" >&2; exit 1; }

    {
      echo "# Generated by scripts/docker.sh for this worktree. Safe to delete."
      echo "WORKTREE_SLUG=$slug"
      echo "WEB_PORT=$web"
      echo "API_PORT=$api"
    } >"$env_file"
  fi

  # shellcheck disable=SC1090
  source "$env_file"
  project="tenora-$mode-$WORKTREE_SLUG"
  web_port="$WEB_PORT"
  api_port="$API_PORT"
  args=(--env-file "$env_file" -p "$project")
else
  project="tenora-$mode"
  web_port=3000
  api_port=8000
  args=()
fi

if [[ "${1:-}" == "ports" ]]; then
  echo "project: $project"
  echo "web:     http://localhost:$web_port"
  echo "api:     http://localhost:$api_port"
  exit 0
fi

echo "[docker] project=$project web=http://localhost:$web_port api=http://localhost:$api_port" >&2
# ${args[@]+...} keeps an empty array from tripping `set -u` on macOS bash 3.2.
exec docker compose ${args[@]+"${args[@]}"} -f "$compose_file" "$@"
